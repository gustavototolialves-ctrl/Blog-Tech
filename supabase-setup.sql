-- Blog Tech: tabela para guardar as reações de todos os visitantes.
-- Execute este script uma única vez no SQL Editor do seu projeto Supabase.

create table if not exists public.article_reactions (
  id bigint generated by default as identity primary key,
  article_id text not null,
  reaction text not null check (reaction in ('amei', 'gostei', 'incrivel', 'engracado', 'nao-gostei')),
  voter_id uuid not null,
  created_at timestamp with time zone not null default now(),
  constraint article_reactions_one_vote_per_browser unique (article_id, voter_id)
);

alter table public.article_reactions enable row level security;

drop policy if exists "Anyone can read reactions" on public.article_reactions;
create policy "Anyone can read reactions"
on public.article_reactions for select
to anon
using (true);

drop policy if exists "Anyone can add reactions" on public.article_reactions;
create policy "Anyone can add reactions"
on public.article_reactions for insert
to anon
with check (
  reaction in ('amei', 'gostei', 'incrivel', 'engracado', 'nao-gostei')
  and length(article_id) between 1 and 100
);

grant select, insert on public.article_reactions to anon;
grant usage, select on sequence public.article_reactions_id_seq to anon;
